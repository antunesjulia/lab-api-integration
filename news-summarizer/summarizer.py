import openai
from config import OPENAI_API_KEY

client = openai.OpenAI(api_key=OPENAI_API_KEY) if OPENAI_API_KEY else None

def summarize_news(news_list):
    """
    Receive the news list and use AI to generate a unique summary.
    """
    if not news_list:
        return "No news to summarize."

    if not client:
        raise ValueError("OPENAI_API_KEY is missing. Add it to the .env file.")

    news_text = ""
    for i, news in enumerate(news_list, 1):
        news_text += f"\n{i}. Title: {news['title']}\nContent: {news['content']}\n"

    # Prompt
    prompt = f"""
    You are a journalist who specializes in quick summaries.
    Read the news story below and write a single paragraph summarizing the main points.
    Be direct and to the point.

    News:
    {news_text}
    """

    try:
        response = client.chat.completions.create(
            model="gpt-4o-mini",
            messages=[
                {"role": "system", "content": "You're a direct assistant."},
                {"role": "user", "content": prompt}
            ],
            temperature=0.7,
            max_tokens=250
        )

        # Return text generated by AI
        return response.choices[0].message.content.strip()

    except Exception as e:
        # Errors
        print(f"Error to generate summary with AI: {e}")
        return None


if __name__ == "__main__":
    from news_api import get_latest_news

    print("Writing the summary...\n")
    summary = summarize_news(get_latest_news())
    print(summary)